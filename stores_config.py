# -*- coding: utf-8 -*-
"""
店舗マスタ（stores_config.py）＝在庫融通アプリの「14店の固定リスト」

【何をするスクリプトか】
店舗セルフアップロード型アプリの店名ドロップダウンに出す、14店の固定リストです。
アプリ本体（streamlit_app.py）と保管庫（gsheet_store.py）が共通で読み込みます。

★店名は「薬VANのファイル名の店名部分（店舗名_YYYYMM）」と、
  従来のコマンド版が使う店名（さと和光／氷川台 等）と同じ表記にそろえています。
  ＝ このドロップダウンで選んだ店名が、そのまま保管庫のキー（raw_<店名>）になります。

★「和光」と「さと和光」は別会社（ソユーズ和光 と 内観堂さと和光）なので、必ず別項目です。

★将来の追加（例：飛鳥薬局22店）は、下の SOYOUZ / NAIKANDO のリストに名前を足すだけ。
  画面の「○/N店」の N は len(STORE_NAMES) から自動計算されるので、
  ここを増やせば分母も自動で増えます（コードの他の場所を直す必要はありません）。

【確定事項（本間部長 2026-07-25）】
  ・「厚生薬局」（ソユーズ店番号07）は閉店・対象外のため、この一覧から除外しました。
    → 画面表示は自動で「○/14店」になります。
  ・各店の表記（例：東立石／柏駅前）が薬VANのファイル名と食い違う場合は、
    この一覧をその表記に直すだけです（分母は自動追従）。

※ venv不要。Windows専用パス。コメント・メッセージはすべて日本語です。
"""

# ソユーズ薬局（9店）… 店番号 01〜10 のうち 07 厚生薬局は閉店で除外
SOYOUZ = [
    '東大泉',    # 01
    '海浜幕張',  # 02
    '自由が丘',  # 03
    '東立石',    # 04
    '鈴木薬局',  # 05
    '大塚',      # 06
    # '厚生薬局',  # 07 ← 閉店・対象外のため除外（2026-07-25 本間部長確定）
    '和光',      # 08 ← ソユーズ和光（内観堂「さと和光」とは別会社）
    '柏',        # 09
    '柏駅前',    # 10
]

# 内観堂薬局（5店）… 店番号 31,32,33,34,35 の並び
NAIKANDO = [
    'みずほ台',  # 31
    'さと和光',  # 32 ← 内観堂さと和光（ソユーズ「和光」とは別会社）
    '氷川台',    # 33
    '徳丸',      # 34
    '下落合',    # 35
]

# ドロップダウンに出す14店（ソユーズ9→内観堂5の順）
STORE_NAMES = SOYOUZ + NAIKANDO

# 会社名を引くための対応表（画面の見出し用）
COMPANY_OF = {}
for _n in SOYOUZ:
    COMPANY_OF[_n] = 'ソユーズ'
for _n in NAIKANDO:
    COMPANY_OF[_n] = '内観堂'

# 店数（○/N の分母）
STORE_COUNT = len(STORE_NAMES)
